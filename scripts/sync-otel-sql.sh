#!/usr/bin/env bash
# Vendors OpenTelemetry Java's SQL grammar and the three classes it uses into sentry core.
#
#   sentry/src/main/jflex/SqlSanitizer.jflex          grammar; JFlex generates AutoSqlSanitizer
#   sentry/src/main/java/io/sentry/vendor/otel/sql/   SqlQuery, SqlDialect, StringUtils
#   sentry/src/main/java/io/sentry/vendor/otel/sql/UPSTREAM   repository, commit and paths
#
# Usage:
#   scripts/sync-otel-sql.sh <ref>     vendor the files at <ref> (commit, tag or branch), print
#                                      upstream's diff since the recorded commit
#   scripts/sync-otel-sql.sh --check   re-derive the vendored files from the recorded commit and
#                                      compare them byte for byte (needs network)
#
# Every change to an upstream file is applied here, never by hand. A change whose expected text
# is missing upstream fails the run, so an upstream edit that touches a changed line shows up
# here instead of silently. After a sync, run
#   ./gradlew :sentry:test --tests 'io.sentry.util.sql.*'
# Exit status: 0 on success, 1 on a failed check or a missing expected text, 2 on usage or
# download errors.
set -euo pipefail

repository="open-telemetry/opentelemetry-java-instrumentation"
root="$(git rev-parse --show-toplevel)"
vendor_dir="$root/sentry/src/main/java/io/sentry/vendor/otel/sql"
meta="$vendor_dir/UPSTREAM"

# Upstream path -> vendored path, relative to the repository roots.
paths=(
  "instrumentation-api-incubator/src/main/jflex/SqlSanitizer.jflex"
  "instrumentation-api-incubator/src/main/java/io/opentelemetry/instrumentation/api/incubator/semconv/db/SqlQuery.java"
  "instrumentation-api-incubator/src/main/java/io/opentelemetry/instrumentation/api/incubator/semconv/db/SqlDialect.java"
  "instrumentation-api/src/main/java/io/opentelemetry/instrumentation/api/internal/StringUtils.java"
)
targets=(
  "sentry/src/main/jflex/SqlSanitizer.jflex"
  "sentry/src/main/java/io/sentry/vendor/otel/sql/SqlQuery.java"
  "sentry/src/main/java/io/sentry/vendor/otel/sql/SqlDialect.java"
  "sentry/src/main/java/io/sentry/vendor/otel/sql/StringUtils.java"
)

die() {
  echo "error: $*" >&2
  exit 2
}

# rewrite <file> <perl substitution>: applies the substitution to the whole file; fails if it
# matched nothing.
rewrite() {
  perl -e '
    my ($file, $expr, $label) = @ARGV;
    local $/;
    open(my $in, "<", $file) or die "cannot read $file: $!";
    my $s = <$in>;
    close($in);
    my $n = eval "\$s =~ $expr";
    die "invalid substitution $expr: $@" if $@;
    if (!$n) {
      print STDERR "expected text not found in $label: $expr\n";
      exit 1;
    }
    open(my $out, ">", $file) or die "cannot write $file: $!";
    print $out $s;
    close($out);
  ' "$1" "$2" "${label:-$1}" || exit 1
}

# header <file> <upstream path> <commit> <changes>: prepends the attribution header (AGENTS.md).
# The upstream license comment stays in place below it.
header() {
  local file="$1" path="$2" commit="$3" changes="$4" tmp
  tmp="$file.header"
  {
    echo "// Adapted from OpenTelemetry Java Instrumentation."
    echo "// Copyright The OpenTelemetry Authors."
    echo "// Licensed under the Apache License, Version 2.0."
    echo "// https://github.com/$repository/blob/$commit/$path"
    echo "// Changes: $changes"
    echo "// Applied by scripts/sync-otel-sql.sh; do not edit this file by hand."
    cat "$file"
  } >"$tmp"
  mv "$tmp" "$file"
}

java_class_changes() {
  local file="$1" from_package="$2"
  rewrite "$file" "s/^package \\Q$from_package\\E;\\n/package io.sentry.vendor.otel.sql;\\n\\nimport org.jetbrains.annotations.ApiStatus;\\n/m"
  rewrite "$file" 's/^(public (?:final |abstract )?class )/\@ApiStatus.Internal\n$1/m'
}

remove_auto_value() {
  local file="$1"
  rewrite "$file" 's/^import com\.google\.auto\.value\.AutoValue;\n//m'
  rewrite "$file" 's/^\@AutoValue\n//mg'
}

jetbrains_nullable() {
  rewrite "$1" 's/^import javax\.annotation\.Nullable;$/import org.jetbrains.annotations.Nullable;/m'
}

string_utils_import() {
  rewrite "$1" 's/\bio\.opentelemetry\.instrumentation\.api\.internal\.StringUtils\b/io.sentry.vendor.otel.sql.StringUtils/g'
}

# transform <index> <file> <commit>: applies every change for upstream file <index> to <file>.
transform() {
  local index="$1" file="$2" commit="$3" semconv="io.opentelemetry.instrumentation.api.incubator.semconv.db"
  case "$index" in
    0)
      rewrite "$file" "s/^package \\Q$semconv\\E;\$/package io.sentry.vendor.otel.sql;/m"
      string_utils_import "$file"
      # Without %scanerror, JFlex throws java.lang.Error on an internal scanner error, which the
      # SDK must not catch (AGENTS.md); SqlLexerException is a RuntimeException.
      rewrite "$file" 's/^(%class AutoSqlSanitizer\n)/$1%scanerror SqlLexerException\n/m'
      header "$file" "${paths[0]}" "$commit" \
        "package and StringUtils import moved to io.sentry.vendor.otel.sql; %scanerror SqlLexerException added."
      ;;
    1)
      java_class_changes "$file" "$semconv"
      string_utils_import "$file"
      jetbrains_nullable "$file"
      remove_auto_value "$file"
      header "$file" "${paths[1]}" "$commit" \
        "package and StringUtils import moved to io.sentry.vendor.otel.sql; javax.annotation.Nullable replaced by org.jetbrains.annotations.Nullable; @ApiStatus.Internal added; @AutoValue removed (AutoValue_SqlQuery is hand-written)."
      ;;
    2)
      java_class_changes "$file" "$semconv"
      jetbrains_nullable "$file"
      remove_auto_value "$file"
      rewrite "$file" 's/^[ \t]*\@AutoValue\.Builder\n//mg'
      rewrite "$file" 's/^import com\.google\.errorprone\.annotations\.CanIgnoreReturnValue;\n//m'
      rewrite "$file" 's/^[ \t]*\@CanIgnoreReturnValue\n//mg'
      header "$file" "${paths[2]}" "$commit" \
        "package moved to io.sentry.vendor.otel.sql; javax.annotation.Nullable replaced by org.jetbrains.annotations.Nullable; @ApiStatus.Internal added; @AutoValue, @AutoValue.Builder and @CanIgnoreReturnValue removed (AutoValue_SqlDialect is hand-written)."
      ;;
    3)
      java_class_changes "$file" "io.opentelemetry.instrumentation.api.internal"
      header "$file" "${paths[3]}" "$commit" \
        "package moved to io.sentry.vendor.otel.sql; @ApiStatus.Internal added."
      ;;
  esac
}

metadata() {
  local commit="$1" path
  echo "# Vendored by scripts/sync-otel-sql.sh; do not edit by hand."
  echo "repository=$repository"
  echo "commit=$commit"
  for path in "${paths[@]}"; do
    echo "file=$path"
  done
}

recorded_commit() {
  [[ -f "$meta" ]] || die "$meta not found"
  sed -n 's/^commit=//p' "$meta"
}

resolve() {
  local ref="$1" lines name
  if [[ "$ref" =~ ^[0-9a-f]{40}$ ]]; then
    echo "$ref"
    return
  fi
  lines="$(git ls-remote "https://github.com/$repository.git")" || die "could not list refs"
  # A peeled annotated tag (^{}) names the commit; then a lightweight tag; then a branch.
  for name in "refs/tags/$ref^{}" "refs/tags/$ref" "refs/heads/$ref"; do
    awk -v name="$name" '$2 == name { print $1; found = 1 } END { exit !found }' <<<"$lines" &&
      return
  done
  die "$ref is neither a full commit hash, a tag nor a branch"
}

# fetch <commit> <dir>: downloads the upstream files at <commit> into <dir>/<index>.
fetch() {
  local commit="$1" dir="$2" i
  for i in "${!paths[@]}"; do
    curl -fsSL "https://raw.githubusercontent.com/$repository/$commit/${paths[$i]}" -o "$dir/$i" ||
      die "could not download ${paths[$i]} at $commit"
  done
}

# derive <commit> <dir>: downloads and transforms the files at <commit>; writes <dir>/out/<index>
# and <dir>/out/UPSTREAM.
derive() {
  local commit="$1" dir="$2" i
  mkdir -p "$dir/new" "$dir/out"
  fetch "$commit" "$dir/new"
  for i in "${!paths[@]}"; do
    cp "$dir/new/$i" "$dir/out/$i"
    label="${paths[$i]} at $commit" transform "$i" "$dir/out/$i" "$commit"
  done
  metadata "$commit" >"$dir/out/UPSTREAM"
}

check() {
  local commit tmp i failed=0
  commit="$(recorded_commit)"
  tmp="$(mktemp -d)"
  # shellcheck disable=SC2064
  trap "rm -rf '$tmp'" EXIT
  derive "$commit" "$tmp"
  for i in "${!paths[@]}"; do
    if ! diff -u "$tmp/out/$i" "$root/${targets[$i]}" >&2; then
      echo "check failed: ${targets[$i]} differs from upstream $commit with the scripted changes" >&2
      failed=1
    fi
  done
  if ! diff -u "$tmp/out/UPSTREAM" "$meta" >&2; then
    echo "check failed: $meta differs from what the script writes" >&2
    failed=1
  fi
  if ((failed)); then
    echo "Vendored files must only change through scripts/sync-otel-sql.sh." >&2
    return 1
  fi
  echo "ok: vendored files match upstream $commit with the scripted changes"
}

sync() {
  local commit old_commit="" tmp i
  commit="$(resolve "$1")"
  if [[ -f "$meta" ]]; then
    old_commit="$(recorded_commit)"
  fi
  tmp="$(mktemp -d)"
  # shellcheck disable=SC2064
  trap "rm -rf '$tmp'" EXIT
  derive "$commit" "$tmp"
  for i in "${!paths[@]}"; do
    mkdir -p "$(dirname "$root/${targets[$i]}")"
    cp "$tmp/out/$i" "$root/${targets[$i]}"
  done
  cp "$tmp/out/UPSTREAM" "$meta"
  echo "vendored $repository at $commit"

  if [[ -n "$old_commit" && "$old_commit" != "$commit" ]]; then
    mkdir -p "$tmp/old"
    fetch "$old_commit" "$tmp/old"
    echo "upstream changes $old_commit..$commit (review them; the tests do not assert outputs):"
    for i in "${!paths[@]}"; do
      diff -u --label "a/${paths[$i]}" --label "b/${paths[$i]}" "$tmp/old/$i" "$tmp/new/$i" || true
    done
  fi
  echo "next: ./gradlew :sentry:test --tests 'io.sentry.util.sql.*'"
}

case "${1:-}" in
  --check) check ;;
  "" | -h | --help) sed -n '2,20p' "$0" | sed 's/^# \{0,1\}//' ;;
  -*) die "unknown option: $1" ;;
  *) sync "$1" ;;
esac
