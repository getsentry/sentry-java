  @Test
  fun `value classes encode inline as their underlying values`() {
    val value =
      WithValueClasses(
        price = Price(999),
        presentPrice = Price(1),
        absentPrice = null,
        presentId = MaybeId("id"),
        absentId = MaybeId(null),
        filterRef = FilterRef(Filter("a", "shoes")),
